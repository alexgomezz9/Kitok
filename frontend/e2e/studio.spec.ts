test('editorial: read A/B, render saved local plan and load the promoted video',async({page})=>{
 await page.goto('/#editorial')
 await expect(page.getByRole('heading',{name:'Comparación local de prueba'})).toBeVisible()
 const before=await page.getByLabel('Vídeo B').getAttribute('src')
 await expect(page.getByText(/Audio A\/B: idéntico/)).toBeVisible()
 await page.getByRole('button',{name:'Renderizar plan guardado · reutiliza audio'}).click()
 await expect(page.getByRole('status').filter({hasText:'Montaje terminado'})).toBeVisible({timeout:25000})
 await expect(page.getByLabel('Vídeo B')).not.toHaveAttribute('src',before!)
 await expect(page.getByLabel('Vídeo B')).toHaveJSProperty('readyState',4)
 await expect(page.getByText(/Audio A\/B: idéntico/)).toBeVisible()
 await page.getByText('Ver fotogramas de revisión').click()
 await expect(page.getByAltText('Fotogramas del montaje B para revisión visual')).toBeVisible()
 await page.screenshot({path:'/tmp/kitok-editorial-ui.png',fullPage:true})
 const download=page.waitForEvent('download')
 await page.getByRole('link',{name:'Descargar B',exact:true}).click()
 expect((await download).suggestedFilename()).toBe('B_improved.mp4')
})
