import { test, expect } from '@playwright/test'

test('an unavailable delivery folder shows a local fallback warning',async({page})=>{
 test.skip(process.env.KITOK_E2E_UNAVAILABLE_DELIVERY!=='1','Requires unavailable-delivery fixture')
 await page.goto('/')
 await expect(page.getByRole('status').filter({hasText:'La carpeta de entrega no está disponible'})).toBeVisible()
 const response=await page.request.get('/api/health')
 expect(response.status()).toBe(200)
 expect((await response.json()).delivery_directory).toMatch(/outputs\/ready$/)
})

test('short: preview, save draft, explicit generation, video and local date',async({page})=>{
 await page.goto('/')
 await expect(page.getByRole('heading',{name:'¿Qué vas a crear?'})).toBeVisible()
 await page.getByLabel('Título',{exact:true}).fill('Short de prueba de navegador')
 await page.getByLabel('Guion completo').fill('Esta es una narración de prueba para comprobar el recorrido del short.')
 await page.getByRole('button',{name:'Comprobar sin generar'}).click()
 await expect(page.getByRole('heading',{name:'Comprobación sin generar'})).toBeVisible()
 await page.screenshot({path:'/tmp/kitok-short-ui.png',fullPage:true})
 await page.getByRole('button',{name:/Guardar borrador y continuar/}).click()
 const dialog=page.getByRole('dialog')
 await expect(dialog.getByRole('button',{name:/Generar vídeo/})).toBeVisible()
 await expect(dialog.locator('video')).toHaveCount(0)
 await dialog.getByRole('button',{name:/Generar vídeo/}).click()
 await expect(dialog.locator('video')).toBeVisible()
 await expect(dialog.locator('video')).toHaveJSProperty('readyState',4)
 await dialog.getByRole('button',{name:'Elegir fecha local'}).click()
 const schedule=page.getByRole('dialog',{name:'Programar vídeo'})
 const tomorrow=new Date(Date.now()+2*86400000).toISOString().slice(0,10)
 await schedule.getByLabel(/Fecha y hora/).fill(`${tomorrow}T19:00`)
 await schedule.getByRole('button',{name:'Guardar fecha'}).click()
 await expect(page.getByRole('button',{name:'Previsualizar envío (dry-run)'})).toBeVisible()
 // Publishing is disabled in the fixture: UI must show the backend's actionable error.
 await page.getByRole('button',{name:'Previsualizar envío (dry-run)'}).click()
 await expect(page.getByRole('alert')).toContainText('PUBLISH_ENABLED')
 const download=page.waitForEvent('download')
 await dialog.getByRole('link',{name:'Abrir archivo / descargar'}).click()
 expect((await download).suggestedFilename()).toMatch(/\.mp4$/)
})

